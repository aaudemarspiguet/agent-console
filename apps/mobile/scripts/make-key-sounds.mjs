// Makes the key sound files the app plays (K-4, handoff T11) from the original
// Rainy 75 takes in sounds-src/rainy-75/ (not bundled). Run from apps/mobile:
//   node scripts/make-key-sounds.mjs
//
// On iOS the keys play through System Sound Services, so they follow the ringer
// volume like the iPhone's own keyboard clicks (the user, 2026-11-13). Apple:
// system sounds play "at the current system audio volume, with no programmatic
// volume control available". So loudness has to be built into the files: each
// take is written at LEVELS_DB below the recording. The first is the keys'
// loudness, chosen by ear on the phone against the iPhone keyboard's own click
// (the user, 2026-11-13: 28 dB down, "still louder but i like its level"; 0 to 24
// dB down were louder still). The next two are for lighter presses.
//
// Writes assets/sounds/rainy-75/m<dB>/v<take>-<down|up>.wav and
// src/keySoundFiles.ts, which requires them (Metro needs static requires).

import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Levels to write, in dB below the recording. */
const LEVELS_DB = [28, 32, 36];

const here = dirname(fileURLToPath(import.meta.url));
const SRC = join(here, '..', 'sounds-src', 'rainy-75');
const OUT = join(here, '..', 'assets', 'sounds', 'rainy-75');
const INDEX = join(here, '..', 'src', 'keySoundFiles.ts');

function scaleWav(file, gain) {
  const b = Buffer.from(readFileSync(file));
  let off = 12;
  while (off < b.length) {
    const id = b.toString('ascii', off, off + 4);
    const size = b.readUInt32LE(off + 4);
    if (id === 'fmt ' && (b.readUInt16LE(off + 8) !== 1 || b.readUInt16LE(off + 22) !== 16)) {
      throw new Error(`${file}: expected 16-bit PCM`);
    }
    if (id === 'data') {
      for (let i = off + 8; i + 1 < off + 8 + size; i += 2) {
        b.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(b.readInt16LE(i) * gain))), i);
      }
    }
    off += 8 + size + (size % 2);
  }
  return b;
}

const takes = readdirSync(SRC)
  .map((f) => f.match(/^v(\d+)-down\.wav$/)?.[1])
  .filter((t) => t !== undefined)
  .map(Number)
  .sort((a, b) => a - b);

rmSync(OUT, { recursive: true, force: true });
for (const db of LEVELS_DB) {
  const dir = join(OUT, `m${db}`);
  mkdirSync(dir, { recursive: true });
  for (const t of takes) {
    for (const stroke of ['down', 'up']) {
      const name = `v${t}-${stroke}.wav`;
      writeFileSync(join(dir, name), scaleWav(join(SRC, name), 10 ** (-db / 20)));
    }
  }
}

const lines = [
  '// Generated by scripts/make-key-sounds.mjs. Do not edit by hand.',
  '',
  '/** Levels available, in dB below the recording. */',
  `export const LEVELS_DB = [${LEVELS_DB.join(', ')}] as const;`,
  'export type LevelDb = (typeof LEVELS_DB)[number];',
  '',
  '/** Rainy 75 takes, press and release, at each level. */',
  'export const KEY_SOUND_FILES: Record<LevelDb, { down: number; up: number }[]> = {',
];
for (const db of LEVELS_DB) {
  lines.push(`  ${db}: [`);
  for (const t of takes) {
    const p = (s) => `require('../assets/sounds/rainy-75/m${db}/v${t}-${s}.wav')`;
    lines.push(`    { down: ${p('down')}, up: ${p('up')} },`);
  }
  lines.push('  ],');
}
lines.push('};', '');
writeFileSync(INDEX, lines.join('\n'));
console.log(`Wrote ${takes.length * 2 * LEVELS_DB.length} files and src/keySoundFiles.ts`);
